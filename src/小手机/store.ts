const Settings = z
  .object({
    mode: z.enum(['mobile', 'desktop']).prefault('desktop'),
    phonePosition: z
      .object({
        x: z.coerce.number().prefault(16),
        y: z.coerce.number().prefault(80),
      })
      .prefault({}),
    open: z.boolean().prefault(true),
    balance: z.coerce.number().prefault(30000),
    backpack: z
      .record(
        z.string().describe('卡牌id'),
        z.object({
          名称: z.string(),
          类型: z.enum(['物品卡', '属性卡', '技能卡', '事件卡', '角色卡', '任务', '朋友卡', '命运卡']),
          等级: z.enum(['F', 'D', 'C', 'B', 'A', 'S', 'SS', 'SSS']),
          描述: z.string().prefault(''),
        }),
      )
      .prefault({}),
    characters: z
      .record(
        z.string().describe('角色名'),
        z.object({
          好感度: z.coerce.number().transform(v => _.clamp(v, 0, 500)).prefault(0),
        }),
      )
      .prefault({}),
  })
  .prefault({});

export const usePhoneStore = defineStore('phone', () => {
  const settings = ref(Settings.parse(getVariables({ type: 'script', script_id: getScriptId() })));

  watchEffect(() => {
    insertOrAssignVariables(klona(settings.value), { type: 'script', script_id: getScriptId() });
  });

  const mode = computed(() => settings.value.mode);
  const open = computed(() => settings.value.open);
  const phonePosition = computed(() => settings.value.phonePosition);
  const characters = computed(() => settings.value.characters);
  const balance = computed(() => settings.value.balance);
  const backpack = computed(() => settings.value.backpack);

  function toggleOpen() {
    settings.value.open = !settings.value.open;
  }

  function setMode(mode: 'mobile' | 'desktop') {
    settings.value.mode = mode;
    if (mode === 'mobile') {
      settings.value.phonePosition = { x: 8, y: 120 };
    } else {
      settings.value.phonePosition = { x: 16, y: 80 };
    }
  }

  function setPhonePosition(pos: { x: number; y: number }) {
    settings.value.phonePosition = { x: pos.x, y: pos.y };
  }

  function setCharAffection(name: string, value: number) {
    const clamped = _.clamp(value, 0, 500);
    if (!settings.value.characters[name]) {
      settings.value.characters[name] = { 好感度: 0 };
    }
    settings.value.characters[name].好感度 = clamped;
  }

  function setBalance(value: number) {
    settings.value.balance = value;
  }

  function addCard(card: { 名称: string; 类型: string; 等级: string; 描述?: string }) {
    const id = `card_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`;
    settings.value.backpack[id] = {
      名称: card.名称,
      类型: card.类型 as any,
      等级: card.等级 as any,
      描述: card.描述 ?? '',
    };
  }

  function removeCard(id: string) {
    delete settings.value.backpack[id];
  }

  const phoneWidth = computed(() => (mode.value === 'mobile' ? 280 : 360));
  const phoneHeight = computed(() => (mode.value === 'mobile' ? 540 : 640));

  return {
    settings,
    mode,
    open,
    phonePosition,
    characters,
    balance,
    backpack,
    phoneWidth,
    phoneHeight,
    toggleOpen,
    setMode,
    setPhonePosition,
    setCharAffection,
    setBalance,
    addCard,
    removeCard,
  };
});
